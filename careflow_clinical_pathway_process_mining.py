# CAREFLOW - STEP 9
# Rule-based pathway conformance checking

import pandas as pd

# Sort activities in chronological order
ordered_log = process_log.sort_values(
    ["case:concept:name", "time:timestamp"]
).copy()

case_results = []

for case_id, group in ordered_log.groupby("case:concept:name"):
    activities = group["concept:name"].tolist()

    # Check basic expected pathway rules
    registration_first = activities[0] == "Registration"

    triage_before_consultation = (
        "Triage" in activities
        and "Doctor Consultation" in activities
        and activities.index("Triage")
        < activities.index("Doctor Consultation")
    )

    treatment_before_discharge = (
        "Treatment" in activities
        and "Discharge" in activities
        and activities.index("Treatment")
        < activities.index("Discharge")
    )

    discharge_last = activities[-1] == "Discharge"

    checks_passed = sum([
        registration_first,
        triage_before_consultation,
        treatment_before_discharge,
        discharge_last
    ])

    case_results.append({
        "Case_ID": case_id,
        "Activities": " → ".join(activities),
        "Registration_First": registration_first,
        "Triage_Before_Consultation": triage_before_consultation,
        "Treatment_Before_Discharge": treatment_before_discharge,
        "Discharge_Last": discharge_last,
        "Checks_Passed": checks_passed,
        "Conformance_Percent": checks_passed / 4 * 100
    })

conformance_report = pd.DataFrame(case_results)

